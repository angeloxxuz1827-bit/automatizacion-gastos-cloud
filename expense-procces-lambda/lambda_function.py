import json

from core.application import Aplication
from aws.s3.client import S3Client
from aws.s3.events import get_bucket_and_key
from aws.s3.key_builder import change_prefix
from ingestion.telegram.client import TelegramAPIError
from ingestion.telegram.service import TelegramService

# Initialize application services.
app = Aplication()
s3 = S3Client()
telegram = TelegramService()


def lambda_handler(event, context):
    """
    AWS Lambda entry point for processing raw Telegram messages.

    This function is triggered by an Amazon S3 ObjectCreated event.
    It retrieves the raw Telegram payload from S3, sends it to the LLM
    for information extraction, stores the LLM response in the
    processed folder, and sends a confirmation message back to the user
    through the Telegram Bot API.

    Args:
        event: AWS Lambda event generated by an S3 notification.
        context: AWS Lambda runtime context.

    Returns:
        A dictionary containing the HTTP status code and response body.
    """

    # Extract the bucket name and object key from the S3 event.
    bucket, raw_key = get_bucket_and_key(event)

    # Retrieve the raw Telegram message stored in S3.
    body = s3.get_json(
        bucket=bucket,
        key=raw_key
    )

    # Execute the LLM to extract structured expense information.
    response_llm = app.llm_run(body)

    # Generate the destination key for the processed response.
    proccesed_key = change_prefix(raw_key, "processed")

    # Store the LLM response in the processed folder.
    s3.put_json(
        bucket=bucket,
        key=proccesed_key,
        data=response_llm
    )

    # Extract the Telegram chat identifier.
    chat_id = body["message"]["chat"]["id"]

    # Parse the JSON content returned by the LLM.
    content_response_llm = json.loads(
        response_llm["choices"][0]["message"]["content"]
    )

    # Build a user-friendly confirmation message.
    message = app.build_expense_message(content_response_llm)

    # Send the confirmation message to the user via Telegram.
    try:
        telegram.send_message(chat_id, message)
    except TelegramAPIError as exc:
        print(f"Telegram send failed: {type(exc).__name__}: {exc}")
        raise
    except Exception as exc:
        # Nunca loguear str(exc): una excepción cruda puede incluir la URL con token.
        print(f"Telegram send failed: {type(exc).__name__}")
        raise RuntimeError("Telegram send failed") from None

    # Return a successful HTTP response.
    return {
        "statusCode": 200,
        "body": json.dumps({"status": "ok"})
    }