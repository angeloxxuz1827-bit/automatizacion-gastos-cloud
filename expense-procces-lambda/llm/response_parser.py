import json


def get_message(response_json: dict) -> str:
    """
    Extracts the message content from a chat completion response.

    Args:
        response_json: Response returned by the language model API.

    Returns:
        The generated message content as a string.
    """

    # Extract and return the generated message.
    return response_json["choices"][0]["message"]["content"]


def get_json(response_json: dict) -> dict:
    """
    Extracts and deserializes the JSON content generated by the language model.

    Args:
        response_json: Response returned by the language model API.

    Returns:
        A dictionary containing the parsed JSON response.
    """

    # Extract the generated message content.
    content = get_message(response_json)

    # Deserialize and return the JSON content.
    return json.loads(content)