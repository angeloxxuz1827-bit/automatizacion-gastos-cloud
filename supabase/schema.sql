-- ============================================================================
-- Esquema objetivo de Supabase (Postgres) para el bot de Telegram.
-- Fecha: 2026-10-21
--
-- Este archivo refleja las migraciones `ajustes_store_supabase` y
-- `restringir_rpc_service_role`.
-- Sirve como referencia y para recrear el esquema en un proyecto nuevo.
-- En la instancia actual las tablas ya existen y las migraciones ya fueron aplicadas.
--
-- RLS queda activo y sin policies: solo `service_role` (la Lambda) puede
-- escribir.
-- ============================================================================

create table if not exists public.clientes (
    chat_id bigint generated by default as identity primary key,
    name varchar not null,
    user_name varchar,
    created_at timestamptz not null default now()
);

create table if not exists public.mensajes (
    id bigint generated by default as identity primary key,
    chat_id bigint not null,
    message_id bigint not null,
    tipo varchar default 'texto',
    original_message varchar,
    state varchar,
    s3_key_proccessed varchar,
    message_date timestamptz,
    created_at timestamptz not null default now(),
    constraint mensajes_chat_message_key unique (chat_id, message_id),
    constraint mensajes_cliente_fk
        foreign key (chat_id) references public.clientes (chat_id)
        on update cascade on delete restrict,
    constraint mensajes_state_check
        check (state is null or state in ('COMPLETO', 'PENDIENTE'))
);

create table if not exists public.gastos (
    gasto_id bigint generated by default as identity primary key,
    message_id bigint,
    categoria varchar,
    subcategoria varchar,
    producto varchar,
    cantidad double precision,
    unidad varchar,
    lugar varchar,
    metodo_pago varchar,
    valor numeric(12, 2),
    moneda varchar not null default 'COP',
    fecha_gasto timestamptz,
    created_at timestamptz not null default now(),
    constraint gastos_message_key unique (message_id),
    constraint gastos_mensaje_fk
        foreign key (message_id) references public.mensajes (id)
        on update cascade on delete restrict
);

create index if not exists gastos_fecha_gasto_idx
    on public.gastos (fecha_gasto);

create index if not exists gastos_categoria_idx
    on public.gastos (categoria);

alter table public.clientes enable row level security;
alter table public.mensajes enable row level security;
alter table public.gastos enable row level security;

-- ============================================================================
-- RPC transaccional: cliente + mensaje + gasto.
-- Es idempotente por (chat_id, message_id) y por message_id en gastos.
-- ============================================================================

create or replace function public.registrar_gasto(
    p_chat_id bigint,
    p_message_id bigint,
    p_name text,
    p_username text,
    p_tipo text,
    p_original_message text,
    p_state text,
    p_s3_key_processed text,
    p_message_date timestamptz,
    p_categoria text,
    p_subcategoria text,
    p_producto text,
    p_cantidad double precision,
    p_unidad text,
    p_lugar text,
    p_metodo_pago text,
    p_valor numeric,
    p_moneda text,
    p_fecha_gasto timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    v_mensaje_id bigint;
    v_gasto_id bigint;
begin
    if p_chat_id is null or p_message_id is null then
        raise exception 'chat_id y message_id son obligatorios';
    end if;

    insert into public.clientes (chat_id, name, user_name)
    values (
        p_chat_id,
        coalesce(nullif(trim(p_name), ''), nullif(trim(p_username), ''), 'Usuario'),
        nullif(trim(p_username), '')
    )
    on conflict (chat_id) do update
    set name = excluded.name,
        user_name = excluded.user_name;

    insert into public.mensajes (
        chat_id,
        message_id,
        tipo,
        original_message,
        state,
        s3_key_proccessed,
        message_date
    )
    values (
        p_chat_id,
        p_message_id,
        coalesce(nullif(trim(p_tipo), ''), 'texto'),
        p_original_message,
        coalesce(nullif(trim(p_state), ''), 'PENDIENTE'),
        p_s3_key_processed,
        p_message_date
    )
    on conflict (chat_id, message_id) do update
    set tipo = excluded.tipo,
        original_message = excluded.original_message,
        state = excluded.state,
        s3_key_proccessed = excluded.s3_key_proccessed,
        message_date = excluded.message_date
    returning id into v_mensaje_id;

    insert into public.gastos (
        message_id,
        categoria,
        subcategoria,
        producto,
        cantidad,
        unidad,
        lugar,
        metodo_pago,
        valor,
        moneda,
        fecha_gasto
    )
    values (
        v_mensaje_id,
        p_categoria,
        p_subcategoria,
        p_producto,
        p_cantidad,
        p_unidad,
        p_lugar,
        p_metodo_pago,
        p_valor,
        coalesce(nullif(trim(p_moneda), ''), 'COP'),
        p_fecha_gasto
    )
    on conflict (message_id) do update
    set categoria = excluded.categoria,
        subcategoria = excluded.subcategoria,
        producto = excluded.producto,
        cantidad = excluded.cantidad,
        unidad = excluded.unidad,
        lugar = excluded.lugar,
        metodo_pago = excluded.metodo_pago,
        valor = excluded.valor,
        moneda = excluded.moneda,
        fecha_gasto = excluded.fecha_gasto
    returning gasto_id into v_gasto_id;

    return jsonb_build_object(
        'message_id', v_mensaje_id,
        'gasto_id', v_gasto_id
    );
end;
$$;

-- Supabase grants EXECUTE to anon/authenticated por defecto en funciones de
-- `public`. Hay que revocarlo explícitamente además de PUBLIC.
revoke all on function public.registrar_gasto(
    bigint, bigint, text, text, text, text, text, text,
    timestamptz, text, text, text, double precision, text, text, text,
    numeric, text, timestamptz
) from public, anon, authenticated;

grant execute on function public.registrar_gasto(
    bigint, bigint, text, text, text, text, text, text,
    timestamptz, text, text, text, double precision, text, text, text,
    numeric, text, timestamptz
) to service_role;
