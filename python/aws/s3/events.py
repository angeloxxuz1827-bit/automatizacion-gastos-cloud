def get_bucket_and_key(event: dict) -> tuple[str, str]:
    """
    Extracts the S3 bucket name and object key from an AWS Lambda event.

    Args:
        event: AWS Lambda event generated by an S3 notification.

    Returns:
        A tuple containing:
            - bucket (str): Name of the S3 bucket.
            - key (str): Object key of the affected S3 object.
    """

    # Retrieve the first event record.
    record = event["Records"][0]

    # Extract the bucket name.
    bucket = record["s3"]["bucket"]["name"]

    # Extract the object key.
    key = record["s3"]["object"]["key"]

    # Return the bucket name and object key.
    return bucket, key