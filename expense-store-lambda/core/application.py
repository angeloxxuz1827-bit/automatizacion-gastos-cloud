import json

from aws.rds.connection import DatabaseConnection

from aws.rds.models.client import Client
from aws.rds.models.message import Message
from aws.rds.models.expense import Expense

from aws.rds.repositories.client_repository import ClientRepository
from aws.rds.repositories.message_repository import MessageRepository
from aws.rds.repositories.expense_repository import ExpenseRepository


class Application:
    """
    Application service responsible for orchestrating the persistence
    of clients, messages, and expenses.

    This class coordinates the interaction between the domain entities
    and their corresponding repositories while keeping all operations
    within the same database transaction.
    """

    def __init__(self, connection):
        """
        Initializes the application service.

        Args:
            connection: Active MySQL database connection shared across
                all repositories.
        """

        # Shared database connection.
        self.connection = connection

        # Repository responsible for client persistence.
        self.client_repository = ClientRepository(connection)

        # Repository responsible for message persistence.
        self.message_repository = MessageRepository(connection)

        # Repository responsible for expense persistence.
        self.expense_repository = ExpenseRepository(connection)

    def process_client(self, content_response_llm):
        """
        Registers the client if it does not already exist.

        Args:
            content_response_llm: Structured response generated by the LLM.
        """

        # Build the client entity from the processed response.
        client = Client(
            chat_id=content_response_llm["ChatId"],
            nombre="Angel Rafael Alfonso Arias",
            username="AngelAlfonso",
            fecha_registro=content_response_llm["Fecha"]
        )

        # Store the client only if it has not been registered before.
        if not self.client_repository.exists(client.chat_id):
            self.client_repository.save(client)

    def process_message(self, content_response_llm) -> int:
        """
        Registers the Telegram message in the database.

        Args:
            content_response_llm: Structured response generated by the LLM.

        Returns:
            The auto-generated primary key (`id`) of the inserted
            message record.
        """

        # Build the message entity.
        message = Message(
            chat_id=content_response_llm["ChatId"],
            message_id=content_response_llm["MessageId"],
            tipo="texto",
            mensaje_original="",
            estado=content_response_llm["Estado"],
            s3_key_processed="",
            fecha_mensaje=content_response_llm["Fecha"]
        )

        # Persist the message and return its generated database ID.
        return self.message_repository.save(message)

    def process_expense(self, content_response_llm, mensaje_id):
        """
        Registers the expense associated with a previously stored message.

        Args:
            content_response_llm: Structured response generated by the LLM.
            mensaje_id: Primary key of the associated record in the
                `mensajes` table.
        """

        # Build the expense entity.
        expense = Expense(
            mensaje_id=mensaje_id,
            categoria=content_response_llm["Categoria"],
            subcategoria=content_response_llm["Subcategoria"],
            producto=content_response_llm["Producto"],
            cantidad=content_response_llm["Cantidad"],
            unidad=content_response_llm["Unidad"],
            lugar=content_response_llm["Lugar"],
            metodo_pago=content_response_llm["MetodoPago"],
            valor=content_response_llm["Valor"],
            moneda=content_response_llm["Moneda"],
            fecha_gasto=content_response_llm["Fecha"]
        )

        # Persist the expense in the database.
        self.expense_repository.save(expense)