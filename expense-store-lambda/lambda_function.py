import json

from aws.s3.client import S3Client
from aws.s3.events import get_bucket_and_key

from aws.rds.connection import DatabaseConnection
from aws.rds.repositories.client_repository import ClientRepository
from aws.rds.repositories.message_repository import MessageRepository
from aws.rds.repositories.expense_repository import ExpenseRepository

from core.application import Application

# Shared S3 client reused across Lambda invocations.
s3 = S3Client()

# Factory responsible for creating database connections.
database_connection = DatabaseConnection()


def lambda_handler(event, context):
    """
    AWS Lambda entry point for persisting processed expense data.

    This function is triggered by an Amazon S3 ObjectCreated event.
    It retrieves the processed LLM response from S3, extracts the
    structured expense information, and stores the client, message,
    and expense records in Amazon RDS within a single transaction.

    Args:
        event: AWS Lambda event generated by an S3 notification.
        context: AWS Lambda runtime context.

    Returns:
        A dictionary containing the HTTP status code and response body.
    """

    # Extract the S3 bucket name and object key from the event.
    bucket, processed_key = get_bucket_and_key(event)

    # Read the processed LLM response stored in Amazon S3.
    response_llm = s3.get_json(
        bucket=bucket,
        key=processed_key
    )

    # Deserialize the structured JSON returned by the LLM.
    content_response_llm = json.loads(
        response_llm["choices"][0]["message"]["content"]
    )

    # Create a new connection to the Amazon RDS database.
    connection = database_connection.get_connection()

    try:
        # Initialize the application layer with the active database connection.
        application = Application(connection)

        # Register the client if it does not already exist.
        application.process_client(content_response_llm)

        # Register the message and retrieve its generated database ID.
        mensaje_id = application.process_message(content_response_llm)

        # Register the expense associated with the stored message.
        application.process_expense(
            content_response_llm,
            mensaje_id
        )

        # Commit all database operations as a single transaction.
        connection.commit()

    except Exception as e:
        # Roll back all pending changes if any operation fails.
        print(e)
        connection.rollback()
        raise

    finally:
        # Always release the database connection.
        connection.close()

    # Return a successful Lambda response.
    return {
        "statusCode": 200,
        "body": json.dumps({"status": "ok"})
    }